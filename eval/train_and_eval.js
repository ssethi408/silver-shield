// Train the word model on 70% of the UCI SMS set, then score the checker on:
//   1. the held-out 30% of UCI (never seen in training),
//   2. a sample of SMS/email from the phishing-multi dataset (different source),
//   3. the team's current-style scam messages in English, Spanish and Chinese.
// Writes checker/model.js and results/metrics.{md,json}.
// Usage: node eval/train_and_eval.js
"use strict";
const fs = require("fs");
const path = require("path");
const engine = require("../checker/engine.js");

const ROOT = path.join(__dirname, "..");
const DATA = path.join(ROOT, "data");
const SEED = 17;

function rng(seed) { // mulberry32
  return function () {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function shuffle(arr, r) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}

// ---- Load UCI ----
const uciPath = path.join(DATA, "SMSSpamCollection");
if (!fs.existsSync(uciPath)) { console.error("Missing data. Run: bash eval/fetch_data.sh"); process.exit(1); }
const uci = fs.readFileSync(uciPath, "utf8").split("\n").filter(Boolean).map(l => {
  const i = l.indexOf("\t"); return { label: l.slice(0, i) === "spam" ? 1 : 0, text: l.slice(i + 1) };
});

// Stratified 70/30 split.
const r = rng(SEED);
const train = [], test = [];
for (const lab of [0, 1]) {
  const rows = shuffle(uci.filter(x => x.label === lab), r);
  const cut = Math.round(rows.length * 0.7);
  train.push(...rows.slice(0, cut)); test.push(...rows.slice(cut));
}

// ---- Train multinomial naive Bayes, export log-likelihood ratios ----
const counts = [new Map(), new Map()]; const totals = [0, 0]; const docs = [0, 0];
for (const { label, text } of train) {
  docs[label]++;
  for (const t of engine.tokenize(text)) { counts[label].set(t, (counts[label].get(t) || 0) + 1); totals[label]++; }
}
const vocab = new Set([...counts[0].keys(), ...counts[1].keys()]);
const V = vocab.size; const w = {};
for (const t of vocab) {
  const c0 = counts[0].get(t) || 0, c1 = counts[1].get(t) || 0;
  if (c0 + c1 < 2) continue; // drop one-off tokens to keep the model small
  const lr = Math.log((c1 + 1) / (totals[1] + V)) - Math.log((c0 + 1) / (totals[0] + V));
  w[t] = Math.round(lr * 1000) / 1000;
}
const model = { prior: Math.log(docs[1] / docs[0]), w, trainedOn: `UCI SMS Spam Collection, ${train.length} messages (70% split, seed ${SEED})` };
fs.writeFileSync(path.join(ROOT, "checker", "model.js"),
  "// Generated by eval/train_and_eval.js. Do not edit by hand.\n" +
  "(function (root) { var m = " + JSON.stringify(model) + ";\n" +
  "if (typeof module !== 'undefined' && module.exports) module.exports = m; else root.SilverShieldModel = m; })(typeof window !== 'undefined' ? window : globalThis);\n");

// ---- Scoring ----
function score(rows, opts) {
  const tab = { scam: { likely_scam: 0, cannot_tell: 0, no_red_flags: 0 }, benign: { likely_scam: 0, cannot_tell: 0, no_red_flags: 0 } };
  const misses = [], falseAlarms = [];
  for (const row of rows) {
    const res = engine.check(row.text, Object.assign({ model }, opts));
    const k = row.label ? "scam" : "benign";
    tab[k][res.verdict]++;
    if (row.label && res.verdict !== "likely_scam") misses.push({ text: row.text, verdict: res.verdict, kind: row.kind });
    if (!row.label && res.verdict === "likely_scam") falseAlarms.push({ text: row.text, flags: res.flags.map(f => f.id), kind: row.kind });
  }
  const nS = rows.filter(x => x.label).length, nB = rows.length - nS;
  const tp = tab.scam.likely_scam, fp = tab.benign.likely_scam;
  return {
    n: rows.length, scams: nS, benign: nB, table: tab,
    accuracy: (tp + (nB - fp)) / rows.length,
    missedScamRate: nS ? (nS - tp) / nS : null,
    scamsCalledNoRedFlags: nS ? tab.scam.no_red_flags / nS : null,
    falseAlarmRate: nB ? fp / nB : null,
    misses, falseAlarms
  };
}

// UCI held-out test
const results = {
  generated: new Date().toISOString().slice(0, 10),
  uciTest: {
    rulesOnly: score(test, { model: null }),
    modelOnly: score(test, { rules: false }),
    combined: score(test, {})
  }
};

// phishing-multi: short texts only (SMS-length), deduped against UCI, 300 per class
const phishPath = path.join(DATA, "texts.json");
if (fs.existsSync(phishPath)) {
  const uciTexts = new Set(uci.map(x => x.text.trim().toLowerCase()));
  const all = JSON.parse(fs.readFileSync(phishPath, "utf8"))
    .filter(x => x.text && x.text.length >= 20 && x.text.length <= 300 && !uciTexts.has(x.text.trim().toLowerCase()))
    .map(x => ({ label: x.label ? 1 : 0, text: x.text }));
  const r2 = rng(SEED + 1);
  const sample = [];
  for (const lab of [0, 1]) sample.push(...shuffle(all.filter(x => x.label === lab), r2).slice(0, 300));
  results.phishingMulti = { combined: score(sample, {}), pool: all.length };
}

// Current-style messages, by language
const cur = JSON.parse(fs.readFileSync(path.join(__dirname, "current_scams.json"), "utf8")).messages
  .map(m => ({ label: m.label === "scam" ? 1 : 0, text: m.text, kind: `${m.lang}/${m.kind}`, lang: m.lang }));
results.current = { all: score(cur, {}) };
for (const lang of ["en", "es", "zh"]) results.current[lang] = score(cur.filter(m => m.lang === lang), {});

// ---- Report ----
const pct = x => x === null ? "n/a" : (x * 100).toFixed(1) + "%";
const row = (name, s) => `| ${name} | ${s.n} (${s.scams} scam / ${s.benign} benign) | ${pct(s.accuracy)} | ${pct(s.missedScamRate)} | ${pct(s.scamsCalledNoRedFlags)} | ${pct(s.falseAlarmRate)} |`;
const tableHead = "| Test set | Messages | Accuracy | Missed scams | Scams told \"no red flags\" | False alarms |\n|---|---|---|---|---|---|";
const breakdown = s => `| | Likely scam | Cannot tell | No red flags |\n|---|---|---|---|\n| Scam | ${s.table.scam.likely_scam} | ${s.table.scam.cannot_tell} | ${s.table.scam.no_red_flags} |\n| Benign | ${s.table.benign.likely_scam} | ${s.table.benign.cannot_tell} | ${s.table.benign.no_red_flags} |`;
const cut = t => t.replace(/\s+/g, " ").slice(0, 140);

let md = `# Silver Shield: measured results\n\nGenerated ${results.generated} by \`npm run eval\`. Only messages marked "likely scam" count as caught; "cannot tell" counts as a miss for scams and as no alarm for benign messages.\n\n`;
md += `## Headline\n\n${tableHead}\n`;
md += row("UCI SMS, held-out 30% (rules + model)", results.uciTest.combined) + "\n";
if (results.phishingMulti) md += row("phishing-multi SMS/email sample (unseen source)", results.phishingMulti.combined) + "\n";
md += row("Current-style messages, all languages", results.current.all) + "\n";
md += `\n## UCI held-out: which part does the work\n\n${tableHead}\n`;
md += row("Red-flag rules only", results.uciTest.rulesOnly) + "\n";
md += row("Word model only", results.uciTest.modelOnly) + "\n";
md += row("Rules + model (shipped)", results.uciTest.combined) + "\n";
md += `\n### Verdict breakdown, UCI held-out\n\n${breakdown(results.uciTest.combined)}\n`;
if (results.phishingMulti) md += `\n### Verdict breakdown, phishing-multi sample\n\n${breakdown(results.phishingMulti.combined)}\n`;
md += `\n## Current-style messages by language\n\n${tableHead}\n`;
for (const lang of ["en", "es", "zh"]) md += row(lang, results.current[lang]) + "\n";
md += `\n### Every current-style message\n\n| Label | Kind | Verdict | Flags |\n|---|---|---|---|\n`;
for (const m of cur) {
  const res = engine.check(m.text, { model });
  md += `| ${m.label ? "scam" : "benign"} | ${m.kind} | ${res.verdict} | ${res.flags.map(f => f.id).join(", ")} |\n`;
}
const ex = (title, list) => list.length ? `\n### ${title}\n\n` + list.slice(0, 8).map(x => `- (${x.verdict || x.flags.join(",")}) ${cut(x.text)}`).join("\n") + "\n" : "";
md += `\n## What it gets wrong (examples)\n`;
md += ex("UCI scams it missed", results.uciTest.combined.misses);
md += ex("UCI benign messages it flagged", results.uciTest.combined.falseAlarms);
if (results.phishingMulti) {
  md += ex("phishing-multi scams it missed", results.phishingMulti.combined.misses);
  md += ex("phishing-multi benign messages it flagged", results.phishingMulti.combined.falseAlarms);
}
md += ex("Current-style scams it missed", results.current.all.misses);
md += ex("Current-style benign messages it flagged", results.current.all.falseAlarms);

fs.mkdirSync(path.join(ROOT, "results"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "results", "metrics.md"), md);
const slim = JSON.parse(JSON.stringify(results, (k, v) => (k === "misses" || k === "falseAlarms") ? v.length : v));
fs.writeFileSync(path.join(ROOT, "results", "metrics.json"), JSON.stringify(slim, null, 2) + "\n");
console.log(md.split("## UCI held-out")[0]);
console.log("Full report: results/metrics.md");
