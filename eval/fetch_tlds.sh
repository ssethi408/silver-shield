#!/usr/bin/env bash
# Regenerate checker/tlds.js from IANA's official list of top-level domains (.com, .org, .xyz, ...).
# The checker uses it to tell a real web address from a broken or made-up one.
set -euo pipefail
cd "$(dirname "$0")/.."
curl -fsSL https://data.iana.org/TLD/tlds-alpha-by-domain.txt | node -e '
let s = ""; process.stdin.on("data", d => (s += d)).on("end", () => {
  const lines = s.split("\n"); const version = lines[0].replace(/^#\s*/, "");
  const tlds = lines.slice(1).map(l => l.trim().toLowerCase()).filter(Boolean);
  require("fs").writeFileSync("checker/tlds.js",
    "// Generated by eval/fetch_tlds.sh from https://data.iana.org/TLD/tlds-alpha-by-domain.txt. Do not edit by hand.\n" +
    "// " + version + " (" + tlds.length + " top-level domains)\n" +
    "(function (root) { var t = \"" + tlds.join(" ") + "\";\n" +
    "if (typeof module !== \"undefined\" && module.exports) module.exports = t; else root.SilverShieldTLDs = t; })(typeof window !== \"undefined\" ? window : globalThis);\n");
  console.log("Wrote checker/tlds.js: " + tlds.length + " TLDs");
});'
